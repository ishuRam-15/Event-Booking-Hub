import { z } from 'zod';

export const VenueBlockSchema = z.object({
  id: z.string().optional(),
  venueId: z.string().optional(),
  name: z.string().min(2, 'Block name must be at least 2 characters'),
  code: z.string().min(1, 'Block code is required (e.g. BLOCK-A)'),
  description: z.string().min(10, 'Description must be at least 10 characters'),
  totalBuiltUpAreaSqFt: z.number().int().positive('Total area must be greater than zero'),
  mainHallAreaSqFt: z.number().int().nonnegative().default(0),
  diningAreaSqFt: z.number().int().nonnegative().default(0),
  stageAreaSqFt: z.number().int().nonnegative().default(0),
  cookingAreaSqFt: z.number().int().nonnegative().default(0),
  guestRoomsCount: z.number().int().nonnegative().default(0),
  carParkingCapacity: z.number().int().nonnegative().default(0),
  seatingCapacity: z.number().int().positive('Seating capacity must be greater than zero'),
  floatingCapacity: z.number().int().nonnegative().default(0),
  isAirConditioned: z.boolean().default(true),
  washrooms: z.object({
    gents: z.number().int().nonnegative().default(2),
    ladies: z.number().int().nonnegative().default(2),
    accessible: z.number().int().nonnegative().default(1),
  }).default({ gents: 2, ladies: 2, accessible: 1 }),
  amenities: z.array(z.string()).default([]),
  pricePerDay: z.number().positive('Price per day must be greater than zero'),
  halfDayPrice: z.number().positive().optional(),
  images: z.array(z.string()).default([]),
  isAvailable: z.boolean().default(true),
});

export const VenueSchema = z.object({
  name: z.string().min(3, 'Venue name must be at least 3 characters'),
  slug: z.string().min(3, 'Slug must be at least 3 characters'),
  tagline: z.string().min(5, 'Tagline is required'),
  description: z.string().min(20, 'Description must be at least 20 characters'),
  category: z.enum([
    'marriage-hall',
    'convention-centre',
    'banquet-hall',
    'party-hall',
    'corporate',
    'outdoor-lawn',
  ]),
  state: z.string().min(2, 'State is required'),
  city: z.string().min(2, 'City is required'),
  area: z.string().min(2, 'Area / Locality is required'),
  address: z.string().min(10, 'Full address is required'),
  pincode: z.string().regex(/^[0-9]{6}$/, 'Must be a valid 6-digit Indian pincode'),
  latitude: z.number(),
  longitude: z.number(),
  googleMapsUrl: z.string().url('Google Maps URL is required'),
  images: z.array(z.string().url()).min(1, 'At least 1 image is required'),
  floorPlanUrl: z.string().url().optional().or(z.literal('')),
  totalBuiltUpAreaSqFt: z.number().positive(),
  minPricePerDay: z.number().positive(),
  maxPricePerDay: z.number().positive(),
  totalSeatingCapacity: z.number().positive(),
  guestRoomsCount: z.number().int().nonnegative().default(0),
  carParkingCapacity: z.number().int().nonnegative().default(0),
  isVerified: z.boolean().default(true),
  isFeatured: z.boolean().default(false),
  facilities: z.array(z.string()).default([]),
  cancellationPolicy: z.string().min(10, 'Cancellation policy is required'),
  securityDeposit: z.number().nonnegative().default(50000),
  advancePaymentPercentage: z.number().int().min(10).max(100).default(25),
  checkInTime: z.string().default('06:00 AM'),
  checkOutTime: z.string().default('11:00 PM'),
  contactPhone: z.string().optional(),
  contactEmail: z.string().email().optional(),
  blocks: z.array(VenueBlockSchema).min(1, 'At least one architectural block is required'),
});

export type VenueInput = z.infer<typeof VenueSchema>;
export type VenueBlockInput = z.infer<typeof VenueBlockSchema>;
